"""Build step, run after adding, removing or converting any asset (python3 tools/build.py; standard library only).

1. js/manifest.js: every image and sound in assets/ with its real size on disk. The game resolves asset names
   through it (no paths or extensions in the code) and the preloader weights its progress bar by the sizes.
2. treasure_tunnel.html: the single-file version: index.html with its CSS and scripts inlined, and every image and
   sound embedded as a data: URL (audio as Ogg Opus, falling back to the original where there is no .ogg).
"""
import base64, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'assets'
MIME = {'.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg', '.ogg': 'audio/ogg', '.m4a': 'audio/mp4', '.mp3': 'audio/mpeg'}
SCRIPTS = ['js/manifest.js', 'js/data.js', 'js/preload.js', 'js/audio.js', 'js/game.js', 'js/editor.js']


def rel(f):
    return f.relative_to(ROOT).as_posix()


def collect():
    images = {f.stem: f for f in sorted(ASSETS.glob('*')) if f.suffix in ('.webp', '.png', '.jpg')}
    audio = {}
    for f in sorted((ASSETS / 'audio').glob('*')):
        if f.suffix == '.ogg':
            audio.setdefault(f.stem, {})['ogg'] = f
        elif f.suffix in ('.m4a', '.mp3'):
            audio.setdefault(f.stem, {})['src'] = f
    return images, audio


def write_manifest(images, audio):
    entry = lambda f: [rel(f), f.stat().st_size]
    m = {'images': {n: entry(f) for n, f in images.items()},
         'audio': {n: {k: entry(f) for k, f in sorted(v.items())} for n, v in audio.items()}}
    lines = ['/* Generated by tools/build.py from the files in assets/: do not edit by hand.',
             '   Every image and sound the game loads, as [path, size on disk in bytes]. Asset names in the code have no',
             '   path or extension: ASSET() and the voice clips look them up here, and the preloader (js/preload.js) weights',
             '   its progress bar by these sizes. Audio: ogg = Ogg Opus, played by Chrome, Edge, Firefox and recent Safari;',
             '   src = the original .m4a/.mp3, used only by browsers that cannot play Ogg Opus. */',
             'window.MANIFEST = {', '  images: {']
    lines += [f'    {json.dumps(n)}: {json.dumps(v)},' for n, v in m['images'].items()]
    lines += ['  },', '  audio: {']
    lines += [f'    {json.dumps(n)}: {json.dumps(v)},' for n, v in m['audio'].items()]
    lines += ['  },', '};', '']
    (ROOT / 'js/manifest.js').write_text('\n'.join(lines), encoding='utf-8')
    return m


def data_url(f):
    return 'data:%s;base64,%s' % (MIME[f.suffix], base64.b64encode(f.read_bytes()).decode())


def write_bundle(images, audio):
    idx = (ROOT / 'index.html').read_text(encoding='utf-8').split('\n')
    head = idx[:idx.index('<link rel="stylesheet" href="css/style.css">')]
    first_script = next(i for i, l in enumerate(idx) if l.startswith('<script src='))
    body = idx[idx.index('<body>') + 1:first_script]
    listed = [l.split('"')[1] for l in idx[first_script:] if l.startswith('<script src=')]
    assert listed == SCRIPTS, f'index.html scripts {listed} differ from {SCRIPTS}'
    rd = lambda p: (ROOT / p).read_text(encoding='utf-8')
    embed = ('<script>window.ASSETS=' + json.dumps({n: data_url(f) for n, f in images.items()})
             + ';window.AUDIO=' + json.dumps({n: data_url(v.get('ogg') or v['src']) for n, v in audio.items()}) + ';</script>')
    scripts = [line for s in SCRIPTS for line in ('<script>', rd(s).rstrip('\n'), '</script>')]  # one tag each, as in index.html
    parts = head + ['<style>', rd('css/style.css').rstrip('\n'), '</style>', '</head>', '<body>'] + body + [embed] + scripts + ['</body>', '</html>', '']
    (ROOT / 'treasure_tunnel.html').write_text('\n'.join(parts), encoding='utf-8')


if __name__ == '__main__':
    images, audio = collect()
    write_manifest(images, audio)
    write_bundle(images, audio)
    size = (ROOT / 'treasure_tunnel.html').stat().st_size
    print(f'js/manifest.js: {len(images)} images, {len(audio)} sounds; treasure_tunnel.html: {size / 1024 / 1024:.2f} MB')
